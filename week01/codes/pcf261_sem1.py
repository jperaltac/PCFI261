# 1. Gráfico de líneas
import numpy as np
import matplotlib.pyplot as plt

def f(t):
    return np.exp(-t/2.0) * np.cos(15.0 * t)

X = np.linspace(2.0, 5.0, 1000)
Y = f(X)

plt.plot(X, Y, 'b-')
plt.xlabel("t")
plt.ylabel("f(t)")
plt.title("Gráfico de línea: f(t) = e^{-t/2} cos(15 t)")
plt.grid(True)
plt.show()

